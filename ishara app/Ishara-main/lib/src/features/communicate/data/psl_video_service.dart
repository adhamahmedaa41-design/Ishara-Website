class PslVideoService {
  PslVideoService._(this._englishToLabel, this._labelToUrl);

  final Map<String, String> _englishToLabel; // english token → label
  final Map<String, String> _labelToUrl;     // label → MP4 url

  static PslVideoService? _instance;
  static Future<PslVideoService> load() async {
    if (_instance != null) return _instance!;

    final mappingRaw = await rootBundle
        .loadString('assets/psl/pk-dictionary-mapping.json');
    final urlsRaw = await rootBundle
        .loadString('assets/psl/pk-dictionary-urls.json');

    final List mapping = jsonDecode(mappingRaw) as List;
    final Map<String, dynamic> urlsRoot =
        jsonDecode(urlsRaw) as Map<String, dynamic>;

    // Build label → url
    final labelToUrl = <String, String>{};
    final groups = urlsRoot['sign-dictionary'] as List? ?? const [];
    for (final g in groups) {
      final files = (g as Map<String, dynamic>)['file_to_url']
              as Map<String, dynamic>? ??
          {};
      files.forEach((file, url) {
        // file is "videos/pk-hfad-1_water.mp4" → label is "pk-hfad-1_water"
        var label = file.toString();
        if (label.startsWith('videos/')) label = label.substring(7);
        if (label.endsWith('.mp4')) {
          label = label.substring(0, label.length - 4);
        }
        labelToUrl[label] = url.toString();
      });
    }

    // Build english → label (first label that lists this English token wins)
    final englishToLabel = <String, String>{};
    for (final group in mapping) {
      final entries = (group as Map<String, dynamic>)['mapping'] as List? ??
          const [];
      for (final m in entries) {
        final mm = m as Map<String, dynamic>;
        final label = mm['label']?.toString() ?? '';
        if (label.isEmpty || !labelToUrl.containsKey(label)) continue;
        final tokens = mm['token'] as Map<String, dynamic>? ?? const {};
        final enList = (tokens['en'] as List? ?? const []).cast<dynamic>();
        for (final t in enList) {
          final key = t.toString().toLowerCase().trim();
          englishToLabel.putIfAbsent(key, () => label);
        }
      }
    }

    _instance = PslVideoService._(englishToLabel, labelToUrl);
    return _instance!;
  }

  /// Every Arabic surface form mapped to a real PSL clip, deduplicated by
  /// English label so the same sign is only listed once. Used by the
  /// Learn → Dictionary tab to show the full word bank.
  List<PslEntry> get allEntries {
    if (_allEntries != null) return _allEntries!;
    final out = <PslEntry>[];
    final seenLabels = <String>{};
    for (final entry in _arabicToEnglish.entries) {
      final english = entry.value.toLowerCase();
      final label = _englishToLabel[english];
      if (label == null) continue;
      if (!seenLabels.add(label)) continue;
      final url = _labelToUrl[label];
      if (url == null) continue;
      out.add(PslEntry(
        arabic: entry.key,
        english: entry.value,
        label: label,
        videoUrl: url,
      ));
    }
    out.sort((a, b) => a.english.toLowerCase().compareTo(b.english.toLowerCase()));
    _allEntries = List.unmodifiable(out);
    return _allEntries!;
  }
  List<PslEntry>? _allEntries;

  /// Resolve a word (Arabic or English surface form) to a sign clip URL.
  ///
  /// Resolution order:
  ///   1. Arabic surface form via `_arabicToEnglish` (raw / normalised
  ///      / lowercased).
  ///   2. English token directly against the PSL `_englishToLabel` index.
  ///
  /// This lets the Talk-tab translator accept mixed-language input
  /// (e.g. "I love أب") without losing matches.
  PslEntry? lookup(String word) {
    final raw = word.trim();
    if (raw.isEmpty) return null;

    final lower = raw.toLowerCase();

    // 1) Arabic path
    final normalised = _normalizeArabic(raw);
    final english = _arabicToEnglish[raw] ??
        _arabicToEnglish[normalised] ??
        _arabicToEnglish[lower];

    String? label;
    String displayEnglish = '';
    String displayArabic = raw;

    if (english != null) {
      label = _englishToLabel[english.toLowerCase()];
      displayEnglish = english;
    } else {
      // 2) English path — strip non-letters in case the user typed
      // punctuation, then look up the token directly.
      final cleaned = lower.replaceAll(RegExp(r"[^a-z' ]"), '').trim();
      if (cleaned.isEmpty) return null;
      label = _englishToLabel[cleaned];
      if (label == null) return null;
      displayEnglish = cleaned;
      displayArabic = raw; // keep the user's original token for display
    }

    if (label == null) return null;
    final url = _labelToUrl[label];
    if (url == null) return null;

    return PslEntry(
      arabic: displayArabic,
      english: displayEnglish,
      label: label,
      videoUrl: url,
    );
  }
}

final pslVideoServiceProvider = FutureProvider<PslVideoService>((ref) async {
  return PslVideoService.load();
});
