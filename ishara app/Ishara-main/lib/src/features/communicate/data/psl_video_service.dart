/// PSL (Pakistan Sign Language) video bank.
///
/// Loads the bundled `pk-dictionary-mapping.json` (English token → label)
/// and `pk-dictionary-urls.json` (label → MP4 URL on GitHub Releases),
/// builds a fast in-memory index, and exposes `lookup(arabicWord)`.
///
/// Resolution path:
///   Arabic word
///     ├─→ direct hit in `_arabicToEnglish` (curated, normalised)
///     └─→ English token
///           ├─→ index entry → label
///           └─→ url table → MP4
///
/// PSL ≠ Arabic Sign Language; this is the closest cross-language
/// approximation we have. Words without a hit return null and the UI
/// shows the existing "no clip" placeholder.
library;

import 'dart:convert';

import 'package:flutter/services.dart' show rootBundle;
import 'package:flutter_riverpod/flutter_riverpod.dart';

class PslEntry {
  const PslEntry({
    required this.arabic,
    required this.english,
    required this.label,
    required this.videoUrl,
  });

  final String arabic;
  final String english;
  final String label; // e.g. pk-hfad-1_water
  final String videoUrl;
}

String _normalizeArabic(String w) => w
    .replaceAll(RegExp(r'[ً-ٰٟـ]'), '') // diacritics + tatweel
    .replaceAll('أ', 'ا')
    .replaceAll('إ', 'ا')
    .replaceAll('آ', 'ا')
    .replaceAll('ة', 'ه')
    .replaceAll('ى', 'ي')
    .replaceAll(RegExp(r'^ال'), '') // strip leading "al-"
    .trim()
    .toLowerCase();

